#!/usr/bin/env python3
"""Build native .strings resources from the reviewed translation source.
Checks missing columns, duplicate keys and printf placeholder agreement.
"""
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
LOCALES = ['zh-Hans', 'zh-Hant', 'ja', 'ko', 'fr', 'de', 'es', 'pt-BR']
rows = {}
for number, line in enumerate((ROOT / 'Localization/ui-translations.tsv').read_text().splitlines(), 1):
    if not line or line.startswith('#'): continue
    values = line.split('|')
    assert len(values) == 9, f'Line {number}: expected 9 columns, got {len(values)}'
    key, *translations = values
    assert key not in rows, f'Duplicate key: {key}'
    placeholders = re.findall(r'%(?:\d+\$)?(?:0\d+)?[d@]', key)
    for locale, value in zip(LOCALES, translations):
        assert value.strip(), f'{locale}: empty {key}'
        assert re.findall(r'%(?:\d+\$)?(?:0\d+)?[d@]', value) == placeholders, f'{locale}: placeholders differ: {key}'
    rows[key] = translations
# Shared musical notation and units stay as written in every locale.
for key in ['BPM', '20 — 300 BPM']:
    rows[key] = [key] * len(LOCALES)
for i, locale in enumerate(['en'] + LOCALES):
    folder = ROOT / 'TheMetronome' / f'{locale}.lproj'
    folder.mkdir(exist_ok=True)
    lines = ['/* Generated by Scripts/build_localizations.py. Edit Localization/ui-translations.tsv. */']
    for key in sorted(rows):
        value = key if locale == 'en' else rows[key][i - 1]
        lines.append(f'{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};')
    (folder / 'Localizable.strings').write_text('\n'.join(lines) + '\n')
print(f'Validated {len(rows)} strings across {len(LOCALES) + 1} languages.')
